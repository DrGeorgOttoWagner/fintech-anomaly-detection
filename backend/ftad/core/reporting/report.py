"""Research report generation (Markdown, HTML, CSV tables, PNG/SVG figures, manifest).

Every number in a report is taken from analysis or experiment results computed from the
uploaded dataset. Explanatory text is generic and parameterised by those numbers.
"""

from __future__ import annotations

import csv
import json
import shutil
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

from ftad import __version__
from ftad.core.eda import AnalysisContext
from ftad.core.eda import analysis as A
from ftad.core.reporting import figures as F
from ftad.core.reporting.document import Doc

AnalysisFn = Callable[[str, Callable[[], dict]], dict]

EVIDENCE_PROVIDERS: list[Callable] = []


def register_evidence_provider(fn: Callable) -> Callable:
    """Domain modules append evidence sections (e.g. an analysis-coverage appendix)."""
    EVIDENCE_PROVIDERS.append(fn)
    return fn


def _write_csv(path: Path, header: list[str], rows: list[list]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def _pct(v: float | None, digits: int = 3) -> str:
    return "—" if v is None else f"{v * 100:.{digits}f}%"


STAT_KEYS = ["count", "mean", "std", "min", "q1", "median", "q3", "max", "skewness", "kurtosis"]


def generate_report(
    out_dir: Path,
    dataset: dict,
    schema_hash: str,
    ctx: AnalysisContext,
    analysis: AnalysisFn,
    experiment: dict | None = None,
    run_details: list[dict] | None = None,
) -> dict:
    cfg = ctx.cfg
    pos, neg = ctx.pos_name, ctx.neg_name
    fw = F.FigureWriter(out_dir / "figures")
    tables = out_dir / "tables"
    created = datetime.now(timezone.utc).isoformat(timespec="seconds")
    doc = Doc(f"Research report — {dataset['name']}")
    doc.note(
        f"Generated by FTAD {__version__} on {created}. All values are computed from the uploaded file "
        f"'{dataset['original_filename']}' (SHA-256 {dataset['sha256'][:16]}…, schema {schema_hash})."
    )

    ov = analysis("overview", lambda: A.overview(ctx))
    cb = ov.get("class_balance")
    value = analysis("value", lambda: A.value_analysis(ctx, cfg.amount_column)) if cfg.amount_column else None
    value_log = analysis("value_log", lambda: A.value_analysis(ctx, cfg.amount_column, log=True)) if value and value.get("log_available") else None
    time_res = analysis("time", lambda: A.time_analysis(ctx)) if cfg.time_column else None
    rel = analysis("relevance", lambda: A.feature_relevance(ctx)) if ctx.has_target else None
    corr = analysis("corr", lambda: A.correlation(ctx))
    pca = analysis("pca", lambda: A.pca_exploration(ctx)) if cfg.pca_features else None
    finds = A.findings(ctx, ov, value, time_res, rel)
    evidence: dict[str, str] = {}

    # 1 Dataset description --------------------------------------------------
    doc.h(1, "1. Dataset description")
    roles = ov["role_counts"]
    doc.table(["Property", "Value"], [
        ["File", dataset["original_filename"]], ["SHA-256 fingerprint", dataset["sha256"]], ["Records", ov["n_records"]],
        ["Columns", ov["n_columns"]], ["Feature columns", ov["n_features"]],
        ["…of which precomputed PCA components", ov["n_pca_features"]], ["Target column", cfg.target],
        ["Positive label", f"{cfg.positive_label} → '{pos}'" if cfg.target else None],
        ["Time column", f"{cfg.time_column} ({cfg.time_kind})" if cfg.time_column else None], ["Amount / value column", cfg.amount_column],
        ["Role counts", ", ".join(f"{k}: {v}" for k, v in sorted(roles.items()))],
    ])
    if cfg.pca_features:
        doc.p(f"{len(cfg.pca_features)} columns are provided already transformed by principal component analysis. Their original variables "
              "are not disclosed; this report describes only their statistical properties and attributes no business meaning to them.")
    evidence["dataset"] = "Section 1"

    # 2 Data quality ---------------------------------------------------------------
    doc.h(1, "2. Data quality summary")
    doc.table(["Check", "Result"], [
        ["Missing cells", ov["total_missing_cells"]], ["Columns with missing values", ov["columns_with_missing"]],
        ["Exact duplicate rows", f"{ov['duplicate_rows']:,} ({_pct(ov['duplicate_rows_pct'])})"],
        ["Identical feature vectors with conflicting labels", ov["duplicate_feature_vectors_with_conflicting_labels"]],
    ])
    doc.ul([w["message"] for w in ov["warnings"]])
    evidence["quality"] = "Section 2"

    # 3 Class distribution --------------------------------------------------------------
    if cb:
        doc.h(1, "3. Class distribution")
        doc.table(["Class", "Label", "Records", "Share"], [
            [neg, "other", cb["n_negative"], _pct(cb["negative_share"])],
            [pos, cfg.positive_label, cb["n_positive"], _pct(cb["prevalence"])],
        ], caption="Class counts computed on all records")
        doc.table(["Measure", "Value"], [
            ["Target column", f"{cfg.target} (binary; positive label {cfg.positive_label} = '{pos}')"],
            ["Positive-class prevalence", _pct(cb["prevalence"], 4)], ["Minority : majority ratio", f"1 : {cb['majority_to_minority']:,.1f}"],
            ["One positive per", f"{cb['one_in_n']:,.1f} records"], ["Majority-class baseline accuracy", _pct(cb["majority_baseline_accuracy"], 4)],
        ])
        fig = F.class_distribution(fw, cb)
        doc.figure(fig)
        _write_csv(tables / "class_distribution.csv", ["class", "label", "count", "share"],
                   [[neg, "other", cb["n_negative"], cb["negative_share"]], [pos, cfg.positive_label, cb["n_positive"], cb["prevalence"]]])
        evidence["class_distribution"] = f"Section 3, Figure {fig['number']}, tables/class_distribution.csv"

    # 4 Descriptive statistics -----------------------------------------------------------
    doc.h(1, "4. Descriptive statistics")
    # The binary target is presented in the class-distribution section, not as a continuous variable.
    num_cols = [c for c in ov["columns"] if "mean" in c and c["name"] != cfg.target]
    _write_csv(tables / "descriptive_statistics.csv", ["column", "role", *STAT_KEYS, "missing", "n_unique"],
               [[c["name"], c["role"], *[c.get(k) for k in STAT_KEYS], c["missing"], c["n_unique"]] for c in num_cols])
    key_cols = [c for c in num_cols if c["name"] in {cfg.time_column, cfg.amount_column}]
    doc.table(["Column", "Mean", "Std", "Min", "Q1", "Median", "Q3", "Max", "Skewness"],
              [[c["name"], c["mean"], c["std"], c["min"], c["q1"], c["median"], c["q3"], c["max"], c.get("skewness")] for c in key_cols],
              caption="Key variables (all records). Full table: tables/descriptive_statistics.csv")
    by_class_rows = []
    for label, res in (("value", value), ("time", time_res)):
        if res and res.get("by_class"):
            col = res["column"]
            for cls in (neg, pos):
                s = res["by_class"][cls]
                by_class_rows.append([col, cls, s["count"], s["mean"], s["std"], s["min"], s["q1"], s["median"], s["q3"], s["max"]])
    if by_class_rows:
        doc.table(["Column", "Class", "Count", "Mean", "Std", "Min", "Q1", "Median", "Q3", "Max"], by_class_rows, caption="Statistics by class")
        _write_csv(tables / "statistics_by_class.csv", ["column", "class", "count", "mean", "std", "min", "q1", "median", "q3", "max"], by_class_rows)
    evidence["descriptive"] = "Section 4, tables/descriptive_statistics.csv, tables/statistics_by_class.csv"

    # 5 EDA visualisations -------------------------------------------------------------------
    doc.h(1, "5. Exploratory data analysis")
    if value:
        col = value["column"]
        doc.h(2, f"5.1 {col}")
        if ctx.has_target:
            f1 = F.value_histograms(fw, value, value_log, col, pos, neg)
            f2 = F.boxplots(fw, value["box"], col, pos, neg)
            doc.figure(f1)
            doc.figure(f2)
            t = value.get("tests") or {}
            if t.get("available"):
                doc.table(["Test", "Statistic", "p-value"], [
                    ["Mann–Whitney U (two-sided)", t["mann_whitney_u"], f"{t['mann_whitney_p']:.3g}"],
                    ["Kolmogorov–Smirnov", t["ks_statistic"], f"{t['ks_p']:.3g}"],
                    ["Rank-biserial correlation (effect size)", t["rank_biserial"], None],
                ], caption=f"{col}: {pos} vs. {neg}")
            bands = value.get("bands") or []
            if bands:
                doc.table(["Band", "Range", "Records", pos, f"{pos} rate"],
                          [[i + 1, f"{b['low']:,.2f} – {b['high']:,.2f}", b["n"], b["n_positive"], _pct(b["positive_rate"])] for i, b in enumerate(bands)],
                          caption=f"{pos} rate across quantile bands of {col}")
                _write_csv(tables / f"{F._slug(col)}_bands.csv", ["band", "low", "high", "n", "n_positive", "positive_rate"],
                           [[i + 1, b["low"], b["high"], b["n"], b["n_positive"], b["positive_rate"]] for i, b in enumerate(bands)])
            evidence["amount"] = f"Section 5.1, Figures {f1['number']}–{f2['number']}"
    if time_res and time_res.get("available"):
        doc.h(2, f"5.2 {time_res['column']}")
        if time_res.get("interpretation_note"):
            doc.note(time_res["interpretation_note"])
        f1 = F.time_series(fw, time_res, pos)
        doc.figure(f1)
        nums = [f1["number"]]
        if ctx.has_target and time_res["kind"] != "ordinal":
            f2 = F.time_rate(fw, time_res, pos)
            doc.figure(f2)
            nums.append(f2["number"])
        _write_csv(tables / "time_bins.csv", ["bin", "start", "end", "n", "n_positive", "positive_rate"],
                   [[r["bin"], r["start"], r["end"], r["n"], r.get("n_positive"), r.get("positive_rate")] for r in time_res["series"]])
        evidence["time"] = f"Section 5.2, Figure(s) {', '.join(map(str, nums))}, tables/time_bins.csv"
    doc.h(2, "5.3 Feature analysis")
    fc = F.correlation_heatmap(fw, corr)
    doc.figure(fc)
    doc.table(["Column A", "Column B", "r"], [[p["a"], p["b"], p["r"]] for p in corr["top_pairs"][:10]], caption="Strongest pairwise correlations")
    if rel and rel.get("available"):
        fr = F.relevance_bars(fw, rel)
        doc.figure(fr)
        _write_csv(tables / "feature_relevance.csv", ["feature", "ks_statistic", "univariate_auc", "point_biserial_r", "cohens_d", "mutual_information", "mean_positive", "mean_negative"],
                   [[r["feature"], r["ks_statistic"], r["univariate_auc"], r["point_biserial_r"], r["cohens_d"], r.get("mutual_information"), r["mean_positive"], r["mean_negative"]] for r in rel["features"]])
        top = [r["feature"] for r in rel["features"][:8]]
        dists = [analysis(f"dist:{c}", lambda c=c: A.class_conditional(ctx, c)) for c in top]
        doc.figure(F.class_conditional_grid(fw, dists, pos, neg))
        if rel.get("mi_note"):
            doc.note(rel["mi_note"])
        doc.note(rel["note"])
    if pca and pca.get("available"):
        fp = F.pca_variance(fw, pca)
        doc.figure(fp)
        doc.note(pca["note"])
    evidence["eda"] = "Section 5"

    # 6 Imbalance discussion -----------------------------------------------------------------
    if cb:
        doc.h(1, "6. Class imbalance and its implications")
        doc.p(
            f"Only {_pct(cb['prevalence'])} of the records belong to the positive class '{pos}' (1 in {cb['one_in_n']:,.0f}). A dataset in which one "
            "class is this rare relative to the other is called imbalanced."
        )
        doc.ul([
            f"Accuracy is uninformative: always predicting '{cb['majority_class']}' yields {_pct(cb['majority_baseline_accuracy'])} accuracy but 0% recall.",
            "Precision, recall, F1 and the area under the precision–recall curve (PR-AUC) describe performance on the rare class; "
            f"the PR-AUC of a random ranking equals the prevalence ({cb['prevalence']:.4f}).",
            f"With {cb['n_positive']:,} positive records in total, every evaluation partition contains few positives, so metric estimates are noisy; "
            "stratified splitting keeps prevalence equal across partitions.",
            "Learning algorithms that minimise overall error are dominated by the majority class; class weighting or resampling of the training data "
            "can shift the decision boundary but changes the meaning of predicted probabilities.",
            "Resampling (undersampling, oversampling, SMOTE) must only be applied to training data; SMOTE records are synthetic and are not observed cases.",
            "The decision threshold controls the trade-off between missed positives and false alarms and should be chosen on validation data.",
        ])
        evidence["imbalance"] = "Sections 3 and 6"

    # 7-10 Experiment ---------------------------------------------------------------------
    completed = [r for r in (run_details or []) if r.get("status") == "completed"]
    if experiment and completed:
        ec = experiment["config"]
        sp = experiment["split"]
        doc.h(1, "7. Splitting methodology")
        doc.p(f"Method: {sp['method']} split with seed {ec['split']['seed']} — train {ec['split']['train']:.0%}, validation "
              f"{ec['split']['validation']:.0%}, test {ec['split']['test']:.0%}. Split indices SHA-256: {sp.get('indices_sha256', '')[:16]}….")
        doc.table(["Partition", "Records", pos, "Prevalence"],
                  [[k.title(), v["n"], v.get("n_positive"), _pct(v.get("prevalence"), 4)] for k, v in sp["partitions"].items()])
        doc.ul(sp.get("notes", []) + sp.get("warnings", []))
        doc.h(1, "8. Model selection")
        doc.table(["Algorithm", "Family", "Score type", "Imbalance", "Train rows", "Train time (s)"],
                  [[r["algorithm_name"], r["family"], r["score_type"], r["imbalance"], r["train_rows_used"], r["train_seconds"]] for r in completed])
        pp = ec["preprocessing"]
        doc.p(f"Preprocessing (fitted on training rows only): numeric imputation {pp['numeric_imputation']}, scaling {pp['scaling']}, "
              f"log-transform of amount {'on' if pp['log_amount'] else 'off'}, application PCA {'on' if pp['pca'] else 'off'}, "
              f"feature selection {pp['feature_selection']}. Mode: {experiment['mode']}.")
        doc.h(1, "9. Evaluation methodology")
        thr = ec["threshold"]
        doc.ul([
            f"Operating threshold policy: {thr['policy']}{'' if thr.get('value') is None else ' (' + str(thr['value']) + ')'}; chosen on the validation partition and frozen before the test partition was scored.",
            "Threshold-free ranking metrics: ROC-AUC and PR-AUC (average precision). Threshold metrics: precision, recall, specificity, F1, MCC, balanced accuracy.",
            "Validation and test partitions keep the original class prevalence; no resampling is applied to them.",
            "Anomaly scores (Isolation Forest, LOF, One-Class SVM) and decision scores are not probabilities.",
            "Test results are reported once per model; selecting among models on test scores would bias the estimate.",
        ])
        doc.h(1, "10. Comparative results")
        rows = []
        for r in completed:
            for part in ("validation", "test"):
                m = r["metrics"][part]
                rows.append([r["algorithm_name"], r["imbalance"], part, m["precision"], m["recall"], m["f1"], m["roc_auc"], m["pr_auc"],
                             m["confusion"]["tp"], m["confusion"]["fp"], m["confusion"]["fn"], r["threshold"]])
        header = ["Algorithm", "Imbalance", "Partition", "Precision", "Recall", "F1", "ROC-AUC", "PR-AUC", "TP", "FP", "FN", "Threshold"]
        doc.table(header, rows, caption="Metrics at the validation-frozen threshold")
        _write_csv(tables / "model_results.csv", [h.lower().replace("-", "_") for h in header], rows)
        prev = sp["partitions"]["test"].get("prevalence")
        f1 = F.model_curves(fw, completed, "validation", sp["partitions"]["validation"].get("prevalence"))
        f2 = F.model_curves(fw, completed, "test", prev)
        f3 = F.confusion_grid(fw, completed, "test", pos, neg)
        for f in (f1, f2, f3):
            doc.figure(f)
        best = max(completed, key=lambda r: r["metrics"]["validation"]["pr_auc"] or -1)
        doc.p(f"Selected by validation PR-AUC: {best['algorithm_name']} [{best['imbalance']}] — validation PR-AUC "
              f"{best['metrics']['validation']['pr_auc']:.4f}; its single test estimate is PR-AUC {best['metrics']['test']['pr_auc']:.4f}, "
              f"recall {best['metrics']['test']['recall']:.3f}, precision {_fmt_opt(best['metrics']['test']['precision'])}.")
        evidence["models"] = "Sections 7–10"
        finds.append(f"Best model by validation PR-AUC: {best['algorithm_name']} [{best['imbalance']}] (test PR-AUC {best['metrics']['test']['pr_auc']:.3f}).")
    else:
        doc.h(1, "7.–10. Machine-learning experiment")
        doc.p("No completed experiment was included in this report. The descriptive and exploratory analysis above does not depend on model training.")

    # 11 Findings / 12 Limitations ------------------------------------------------------------
    doc.h(1, "11. Main findings")
    doc.ul(finds)
    doc.h(1, "12. Limitations")
    lim = [
        "All findings are associations observed in this single dataset; they do not establish causal mechanisms.",
        "Statistical significance with very large samples does not imply practical relevance; effect sizes are reported alongside p-values.",
    ]
    if cfg.pca_features:
        lim.append("Most features are anonymised principal components, which prevents substantive interpretation of individual predictors.")
    if cfg.time_kind == "elapsed_seconds" and time_res:
        lim.append(f"The data covers about {time_res['span_seconds'] / 86400:.1f} days of elapsed time without calendar dates; seasonal effects cannot be assessed.")
    if cb and cb["n_positive"] < 1000:
        lim.append(f"With only {cb['n_positive']:,} positive records, test-set metrics rest on few cases and carry wide uncertainty.")
    if ov["duplicate_rows"]:
        lim.append(f"{ov['duplicate_rows']:,} duplicate rows were retained as recorded; they may inflate apparent performance if duplicates fall into different partitions.")
    if completed:
        lim.append("Model results depend on the chosen split seed and hyperparameters; repeated splits or cross-validation would quantify their variability.")
    doc.ul(lim)

    for provider in EVIDENCE_PROVIDERS:
        provider(doc, ctx, evidence, ov, value, time_res, completed)

    (out_dir / "report.md").write_text(doc.markdown(), encoding="utf-8")
    (out_dir / "report.html").write_text(doc.html(out_dir / "figures"), encoding="utf-8")
    manifest = {
        "ftad_version": __version__, "created_at": created, "dataset": {k: dataset[k] for k in ("id", "original_filename", "sha256", "n_rows", "n_cols")},
        "schema_hash": schema_hash, "schema": cfg.model_dump(), "experiment_id": experiment["id"] if experiment else None,
        "figures": fw.items, "evidence": evidence,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, default=str))
    return manifest


def _fmt_opt(v):
    return "undefined" if v is None else f"{v:.3f}"


def list_files(root: Path) -> list[dict]:
    return [{"path": str(p.relative_to(root)), "bytes": p.stat().st_size} for p in sorted(root.rglob("*")) if p.is_file()]


def zip_dir(root: Path, dest: Path) -> Path:
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(root.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(root))
    return dest


def export_copy(src: Path, export_root: Path, name: str) -> Path:
    dest = export_root / name
    if dest.exists():
        raise FileExistsError(f"{dest} already exists.")
    shutil.copytree(src, dest)
    return dest
